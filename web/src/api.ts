// API client for vault-web: JSON in and out, the CSRF header on state-changing
// requests, and the rule that a 401 means the vault is locked.
//
// Secrets are addressed by title, percent-encoded by `secretPath`.
//
// Security: the CSRF token lives only in this object's private field (memory), never
// in localStorage, sessionStorage or a cookie. The session cookie is HttpOnly and
// handled by the browser alone.

import type { AuditEvent } from "./audit-log.js";
import { secretPath } from "./secrets.js";

/** What the server says about an unlocked session. */
export interface SessionInfo {
  csrf_token: string;
  vaultname: string;
  idle_timeout_minutes: number;
}

/** The body of a create or unlock request. */
export interface UnlockRequest {
  vaultname: string;
  master_password: string;
  idle_timeout_minutes?: number;
}

/** A custom field in the secret list: its name and whether it is hidden, never its value. */
export interface FieldName {
  name: string;
  hidden: boolean;
}

/**
 * The fields both secret views carry: what identifies a secret and whether it has a
 * password (never its value). Timestamps are Unix seconds.
 */
export interface SecretFields {
  title: string;
  username: string | null;
  url: string | null;
  tags: string[];
  has_password: boolean;
  created_at: number;
  updated_at: number;
}

/** One secret in the list from `GET /api/secrets`. Holds no notes or custom field value. */
export interface SecretSummary extends SecretFields {
  has_notes: boolean;
  custom_fields: FieldName[];
}

/** A custom field in the secret detail: plain ones carry their value, hidden ones none. */
export type CustomFieldView = { name: string; hidden: false; value: string } | { name: string; hidden: true };

/**
 * One secret from `GET /api/secrets/{title}`: every non-hidden field; hidden fields are
 * named only (`has_password`, custom fields with `hidden: true`).
 */
export interface SecretDetail extends SecretFields {
  notes: string | null;
  custom_fields: CustomFieldView[];
}

/** A hidden value in an add or edit request: the new value, or keep the stored one. */
export type HiddenInput = string | { unchanged: true };

/** A custom field in an add or edit request. */
export interface CustomFieldRequest {
  name: string;
  hidden: boolean;
  value: HiddenInput;
}

/**
 * The body of `POST /api/secrets` and `PUT /api/secrets/{title}`: the whole secret.
 * A left-out password is generated by the server.
 */
export interface SecretRequest {
  title: string;
  username?: string;
  password?: HiddenInput;
  url?: string;
  notes?: string;
  tags: string[];
  custom_fields: CustomFieldRequest[];
}

/** A saved secret, masked as in the detail view, and whether the server generated its password. */
export interface SavedSecret extends SecretDetail {
  password_generated: boolean;
}

/** The field name a reveal request uses for a secret's password; no custom field can have it. */
export const PASSWORD_FIELD = "password";

/** The body of a reveal response: the one hidden value asked for. */
interface Revealed {
  value: string;
}

/** A backup as downloaded: the vault file's bytes and the name to save them under. */
export interface Backup {
  name: string;
  data: Blob;
}

/** The name a backup is saved under when the server's name can't be used. */
const FALLBACK_BACKUP_NAME = "vault-backup.vault";

/**
 * A backup file name the server may give: `<vaultname>-r<revision>.vault`. The
 * vaultname part mirrors `vault-core`'s `Vaultname` rule (1-32 lowercase letters,
 * digits, `-` or `_`, starting with a letter or digit).
 */
const BACKUP_NAME = /^[a-z0-9][a-z0-9_-]{0,31}-r\d{1,20}\.vault$/;

/** Shown when a failed response carries no usable `{"error": ...}` body. */
const GENERIC_ERROR = "request failed";

/** The endpoint whose 401 means a failed unlock rather than a locked session. */
const UNLOCK_PATH = "/api/unlock";

/**
 * One problem of a refused secret: the request field, the 0-based index of the tag or
 * custom field, for a custom field whether its name or value is at fault, and the
 * server's message (which never contains the value).
 */
/** The part of a custom field a {@link FieldProblem} is about. */
export type CustomFieldPart = "name" | "value";

export interface FieldProblem {
  field: string;
  index?: number;
  part?: CustomFieldPart;
  message: string;
}

/**
 * A failed API call: the HTTP status, the server's message and, for a validation
 * error, the request field at fault; for a refused secret, every problem in `fields`.
 *
 * @example
 * if (err instanceof ApiError && err.field === "vaultname") showFieldError(err.message);
 */
export class ApiError extends Error {
  readonly status: number;
  readonly field: string | undefined;
  readonly fields: readonly FieldProblem[];

  /**
   * An error for a response with `status`, `message`, an optional `field` and, for a
   * refused secret, its `fields`.
   *
   * @example
   * throw new ApiError(400, "vaultname taken", "vaultname");
   */
  constructor(status: number, message: string, field?: string, fields: readonly FieldProblem[] = []) {
    super(message);
    this.name = "ApiError";
    this.status = status;
    this.field = field;
    this.fields = fields;
  }
}

/**
 * The vault-web API. Keeps the CSRF token from create, unlock or the session check
 * and sends it in `X-CSRF-Token` on every POST, PUT and DELETE.
 *
 * Any 401 (except from unlock, where it means a wrong vaultname or master password)
 * wipes the token and calls `onLocked`, which must wipe all other vault data and show
 * the unlock page.
 *
 * @example
 * const api = new Api(fetch.bind(window), () => showUnlockPage());
 * const session = await api.unlock({ vaultname: "alice", master_password: password });
 */
export class Api {
  readonly #fetch: typeof fetch;
  readonly #onLocked: () => void;
  #csrfToken: string | null = null;

  /**
   * A client sending requests with `fetchFn`, calling `onLocked` when the server says
   * the session has ended.
   *
   * @example
   * const api = new Api(fetch.bind(window), onLocked);
   */
  constructor(fetchFn: typeof fetch, onLocked: () => void) {
    this.#fetch = fetchFn;
    this.#onLocked = onLocked;
  }

  /**
   * Creates a vault; the server returns it unlocked.
   *
   * @example
   * await api.createVault({ vaultname: "alice", master_password: password, idle_timeout_minutes: 10 });
   */
  async createVault(request: UnlockRequest): Promise<SessionInfo> {
    return this.#open("/api/vaults", request);
  }

  /**
   * Unlocks a vault. A wrong vaultname or master password rejects with a 401
   * {@link ApiError} and does not call `onLocked`.
   *
   * @example
   * await api.unlock({ vaultname: "alice", master_password: password });
   */
  async unlock(request: UnlockRequest): Promise<SessionInfo> {
    return this.#open(UNLOCK_PATH, request);
  }

  /**
   * The current session, if the cookie still names an unlocked one; used on page load.
   * Restores the CSRF token, which a reload loses.
   *
   * @example
   * const session = await api.session().catch(() => null);
   */
  async session(): Promise<SessionInfo> {
    const info = (await this.#request("GET", "/api/session")) as SessionInfo;
    this.#csrfToken = info.csrf_token;
    return info;
  }

  /**
   * Locks the vault on the server and forgets the CSRF token.
   *
   * @example
   * await api.lock();
   */
  async lock(): Promise<void> {
    try {
      await this.#request("POST", "/api/lock");
    } finally {
      this.#csrfToken = null;
    }
  }

  /**
   * The vault's secrets, sorted by title ignoring case, without hidden values.
   *
   * @example
   * const secrets = await api.listSecrets();
   */
  async listSecrets(): Promise<SecretSummary[]> {
    const body = (await this.#request("GET", "/api/secrets")) as { secrets: SecretSummary[] };
    return body.secrets;
  }

  /**
   * The secret titled `title`, with hidden fields named only. An unknown title rejects
   * with a 404 {@link ApiError}.
   *
   * @example
   * const github = await api.getSecret("GitHub");
   */
  async getSecret(title: string): Promise<SecretDetail> {
    return (await this.#request("GET", secretPath(title))) as SecretDetail;
  }

  /**
   * The value of one hidden field of the secret titled `title`: `"password"` or a
   * hidden custom field's name ({@link PASSWORD_FIELD} for the password). The server records each reveal in the audit log.
   *
   * Security: returns the value without keeping it; the caller decides where it lives
   * and for how long. An unknown title or field rejects with a 404 {@link ApiError}.
   *
   * @example
   * const password = await api.revealField("GitHub", PASSWORD_FIELD);
   */
  async revealField(title: string, field: string): Promise<string> {
    const body = (await this.#request("POST", `${secretPath(title)}/reveal`, { field })) as Revealed;
    return body.value;
  }

  /**
   * Adds a secret; a left-out password is generated by the server. A taken title
   * rejects with a 409 {@link ApiError} for the `title` field, a field breaking the
   * rules with a 400 naming it, a full vault with a 413 (the session stays open). The
   * server saves it at once and records it in the audit log.
   *
   * @example
   * const saved = await api.addSecret(secretRequest(values));
   */
  async addSecret(request: SecretRequest): Promise<SavedSecret> {
    return (await this.#request("POST", "/api/secrets", request)) as SavedSecret;
  }

  /**
   * Replaces the secret titled `request.title` as a whole; the title can't change.
   * Hidden values sent as `{"unchanged": true}` keep their stored value, so the
   * browser never needs them. A full vault rejects with a 413 {@link ApiError}; the
   * session stays open.
   *
   * @example
   * await api.editSecret({ ...secretRequest(values), title: secret.title });
   */
  async editSecret(request: SecretRequest): Promise<SavedSecret> {
    return (await this.#request("PUT", secretPath(request.title), request)) as SavedSecret;
  }

  /**
   * Deletes the secret titled `title`; ask the user to confirm first. An unknown
   * title rejects with a 404 {@link ApiError}.
   *
   * @example
   * if (window.confirm(`Delete ${title}?`)) await api.deleteSecret(title);
   */
  async deleteSecret(title: string): Promise<void> {
    await this.#request("DELETE", secretPath(title));
  }

  /**
   * Changes the master password. The server then locks the vault's other sessions and
   * reissues this one; the new CSRF token is kept. A wrong current master password
   * rejects with a 400 {@link ApiError} for `current_master_password` (the third in a
   * row ends the session: a 401, so `onLocked` runs), a new one breaking the rules with
   * a 400 for `new_master_password`.
   *
   * @example
   * await api.changeMasterPassword(current.input.value, next.input.value);
   */
  async changeMasterPassword(current: string, next: string): Promise<SessionInfo> {
    const info = (await this.#request("POST", "/api/master-password", {
      current_master_password: current,
      new_master_password: next,
    })) as SessionInfo;
    this.#csrfToken = info.csrf_token;
    return info;
  }

  /**
   * A backup of the vault: its encrypted file exactly as stored, and the name the
   * server gives it ({@link backupFileName}). The server records it as made.
   *
   * @example
   * const backup = await api.downloadBackup();
   */
  async downloadBackup(): Promise<Backup> {
    const response = await this.#send("POST", "/api/backup");
    return { name: backupFileName(response.headers.get("content-disposition")), data: await response.blob() };
  }

  /**
   * Up to `limit` (1-1000) of the vault's newest audit events, newest first.
   *
   * @example
   * const events = await api.auditLog(20);
   */
  async auditLog(limit: number): Promise<AuditEvent[]> {
    const body = (await this.#request("GET", `/api/audit-log?limit=${limit}`)) as { events: AuditEvent[] };
    return body.events;
  }

  /**
   * Posts a create or unlock request and keeps the returned CSRF token.
   *
   * @example
   * return this.#open("/api/unlock", request);
   */
  async #open(path: string, request: UnlockRequest): Promise<SessionInfo> {
    const info = (await this.#request("POST", path, request)) as SessionInfo;
    this.#csrfToken = info.csrf_token;
    return info;
  }

  /**
   * Sends one request and returns its parsed JSON body (`undefined` for 204).
   *
   * @example
   * const info = await this.#request("GET", "/api/session");
   */
  async #request(method: string, path: string, body?: unknown): Promise<unknown> {
    const response = await this.#send(method, path, body);
    return response.status === 204 ? undefined : await response.json();
  }

  /**
   * Sends one request and returns the successful response; a failure throws its
   * {@link ApiError}, and a 401 (outside unlock) wipes the token and calls `onLocked`.
   *
   * @example
   * const response = await this.#send("POST", "/api/backup");
   */
  async #send(method: string, path: string, body?: unknown): Promise<Response> {
    const headers: Record<string, string> = {};
    if (body !== undefined) {
      headers["content-type"] = "application/json";
    }
    if (method !== "GET" && this.#csrfToken !== null) {
      headers["x-csrf-token"] = this.#csrfToken;
    }
    const init: RequestInit = { method, headers, credentials: "same-origin", cache: "no-store" };
    if (body !== undefined) {
      init.body = JSON.stringify(body);
    }
    const response = await this.#fetch(path, init);
    if (response.ok) {
      return response;
    }
    const error = await errorFrom(response);
    if (response.status === 401) {
      this.#csrfToken = null;
      if (path !== UNLOCK_PATH) {
        this.#onLocked();
      }
    }
    throw error;
  }
}

/**
 * The file name from a backup response's `Content-Disposition`, if it is a plain
 * `<vaultname>-r<revision>.vault`; anything else (missing, a path) gives a fixed name.
 *
 * Security: only a name matching {@link BACKUP_NAME} is used, so a response can't
 * suggest a path or a misleading file type to save under.
 *
 * @example
 * backupFileName('attachment; filename="alice-r3.vault"'); // "alice-r3.vault"
 */
export function backupFileName(disposition: string | null): string {
  const name = /filename="([^"]*)"/.exec(disposition ?? "")?.[1];
  return name !== undefined && BACKUP_NAME.test(name) ? name : FALLBACK_BACKUP_NAME;
}

/**
 * The {@link ApiError} for a failed `response`, from its `{"error", "field"}` or
 * `{"error", "fields"}` body or, failing that, a generic message.
 *
 * @example
 * throw await errorFrom(response);
 */
async function errorFrom(response: Response): Promise<ApiError> {
  try {
    const body: unknown = await response.json();
    if (typeof body === "object" && body !== null && "error" in body && typeof body.error === "string") {
      const field = "field" in body && typeof body.field === "string" ? body.field : undefined;
      const fields = "fields" in body ? fieldProblems(body.fields) : [];
      return new ApiError(response.status, body.error, field, fields);
    }
  } catch {
    // Not JSON: fall through to the generic message.
  }
  return new ApiError(response.status, GENERIC_ERROR);
}

/**
 * The well-formed {@link FieldProblem}s in a response's `fields`; anything else is
 * dropped.
 *
 * @example
 * fieldProblems([{ field: "title", message: "bad title" }, 42]); // just the first
 */
function fieldProblems(fields: unknown): FieldProblem[] {
  if (!Array.isArray(fields)) {
    return [];
  }
  const problems: FieldProblem[] = [];
  for (const entry of fields as unknown[]) {
    if (typeof entry !== "object" || entry === null) {
      continue;
    }
    const { field, index, part, message } = entry as Record<string, unknown>;
    const validIndex = index === undefined || (typeof index === "number" && Number.isInteger(index) && index >= 0);
    const validPart = part === undefined || part === "name" || part === "value";
    if (typeof field !== "string" || typeof message !== "string" || !validIndex || !validPart) {
      continue;
    }
    const problem: FieldProblem = { field, message };
    if (index !== undefined) {
      problem.index = index as number;
    }
    if (part !== undefined) {
      problem.part = part as CustomFieldPart;
    }
    problems.push(problem);
  }
  return problems;
}
